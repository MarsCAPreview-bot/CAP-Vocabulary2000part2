const tabs = document.querySelector("#unitTabs");
const sentenceList = document.querySelector("#sentenceList");
const vocabGrid = document.querySelector("#vocabGrid");
const title = document.querySelector("#unitTitle");
const kind = document.querySelector("#unitKind");
const toggleAllBtn = document.querySelector("#toggleAllBtn");
let activeUnit = localStorage.getItem("english-active-unit") || "31";
if (!lessons[activeUnit]) activeUnit = "31";

function makeTab(unit) {
  const button = document.createElement("button");
  button.className = "tab";
  button.type = "button";
  button.role = "tab";
  button.textContent = `Unit ${unit}`;
  button.addEventListener("click", () => renderUnit(unit));
  return button;
}

function flipCard(card) {
  const flipped = card.classList.toggle("is-flipped");
  card.setAttribute("aria-pressed", String(flipped));
  updateToggleLabel();
}

function renderUnit(unit) {
  activeUnit = String(unit);
  localStorage.setItem("english-active-unit", activeUnit);
  const lesson = lessons[activeUnit];
  title.textContent = lesson.title;
  kind.textContent = `UNIT ${activeUnit} · ${lesson.kind}`;
  document.title = `Unit ${activeUnit} ${lesson.title}｜七年級英文互動學習`;

  [...tabs.children].forEach((tab, index) => {
    const selected = Object.keys(lessons)[index] === activeUnit;
    tab.setAttribute("aria-selected", String(selected));
    tab.tabIndex = selected ? 0 : -1;
  });

  sentenceList.replaceChildren(...lesson.sentences.map((item, index) => {
    const [speaker, english, chinese, grammar] = item;
    const card = document.createElement("button");
    card.type = "button";
    card.className = "sentence-card";
    card.setAttribute("aria-pressed", "false");
    card.setAttribute("aria-label", `第 ${index + 1} 句：${english}。點擊查看中文和文法`);
    card.innerHTML = `<span class="sentence-front"><span class="sentence-number">${index + 1}</span>${speaker ? `<span class="speaker">${speaker}</span>` : ""}<span class="sentence-text">${english}</span></span><span class="sentence-back"><span class="back-english">${speaker ? `${speaker}: ` : ""}${english}</span><span class="translation">${chinese}</span><span class="grammar"><strong>文法重點：</strong>${grammar}</span></span>`;
    card.addEventListener("click", () => flipCard(card));
    return card;
  }));

  vocabGrid.replaceChildren(...lesson.words.map(item => {
    const [word, phonetic, part, meaning] = item;
    const card = document.createElement("div");
    card.className = "word-card";
    card.tabIndex = 0;
    card.role = "button";
    card.setAttribute("aria-pressed", "false");
    card.setAttribute("aria-label", `${word}，點擊查看中文、音標和詞性`);
    card.innerHTML = `<div class="word-front"><span class="word">${word}</span><span class="flip-cue">點擊查看解釋 ↻</span></div><div class="word-back"><span class="phonetic">${phonetic}</span><span class="part">${part}</span><p class="meaning">${meaning}</p><span class="flip-cue">點擊翻回英文 ↻</span></div><button class="speaker-button" type="button" aria-label="播放 ${word} 的發音" title="播放發音">🔊</button>`;
    card.addEventListener("click", event => {
      if (!event.target.closest(".speaker-button")) flipCard(card);
    });
    card.addEventListener("keydown", event => {
      if ((event.key === "Enter" || event.key === " ") && !event.target.closest(".speaker-button")) {
        event.preventDefault(); flipCard(card);
      }
    });
    card.querySelector(".speaker-button").addEventListener("click", event => {
      event.stopPropagation(); speak(word, event.currentTarget);
    });
    return card;
  }));
  updateToggleLabel();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function speak(word, button) {
  if (!("speechSynthesis" in window)) {
    alert("這台裝置目前無法使用語音播放功能。"); return;
  }
  speechSynthesis.cancel();
  const utterance = new SpeechSynthesisUtterance(word);
  utterance.lang = "en-US";
  utterance.rate = .78;
  const voices = speechSynthesis.getVoices();
  utterance.voice = voices.find(v => v.lang === "en-US") || voices.find(v => v.lang.startsWith("en")) || null;
  button.textContent = "◼";
  utterance.onend = utterance.onerror = () => button.textContent = "🔊";
  speechSynthesis.speak(utterance);
}

function updateToggleLabel() {
  const cards = [...sentenceList.querySelectorAll(".sentence-card")];
  toggleAllBtn.textContent = cards.length && cards.every(c => c.classList.contains("is-flipped")) ? "全部收起" : "全部顯示";
}

toggleAllBtn.addEventListener("click", () => {
  const cards = [...sentenceList.querySelectorAll(".sentence-card")];
  const show = !cards.every(c => c.classList.contains("is-flipped"));
  cards.forEach(card => {
    card.classList.toggle("is-flipped", show);
    card.setAttribute("aria-pressed", String(show));
  });
  updateToggleLabel();
});

document.querySelector("#resetBtn").addEventListener("click", () => {
  document.querySelectorAll(".is-flipped").forEach(card => {
    card.classList.remove("is-flipped");
    card.setAttribute("aria-pressed", "false");
  });
  speechSynthesis?.cancel();
  updateToggleLabel();
  document.querySelector("#readingHeading").scrollIntoView({ behavior: "smooth", block: "start" });
});

